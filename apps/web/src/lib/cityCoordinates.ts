/**
 * پاکسازی و یکسان‌سازی کاراکترهای فارسی برای جستجوی نام شهرها
 */
export function normalizeCityName(name?: string | null): string {
  if (!name || typeof name !== 'string') return '';
  return name
    .trim()
    .replace(/[\u200c\u200b]/g, '') // حذف نیم‌فاصله برای مقایسه آسان
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/ة/g, 'ه')
    .replace(/آ/g, 'ا')
    .replace(/^(شهر|شهرستان|استان)\s+/g, '') // حذف پیشوندهای متداول
    .trim();
}

/**
 * یافتن مختصات جغرافیایی یک شهر بر اساس نام
 */
export function findCityCoordinates(cityName?: string | null): LatLng | null {
  if (!cityName) return null;
  const raw = cityName.trim();
  if (IRAN_CITIES_COORDINATES[raw]) {
    return IRAN_CITIES_COORDINATES[raw];
  }

  const normalized = normalizeCityName(cityName);
  if (!normalized) return null;

  for (const [key, coords] of Object.entries(IRAN_CITIES_COORDINATES)) {
    if (normalizeCityName(key) === normalized) {
      return coords;
    }
  }

  // جستجوی زیررشته‌ای
  for (const [key, coords] of Object.entries(IRAN_CITIES_COORDINATES)) {
    const normKey = normalizeCityName(key);
    if (normKey.includes(normalized) || normalized.includes(normKey)) {
      return coords;
    }
  }

  return null;
}
